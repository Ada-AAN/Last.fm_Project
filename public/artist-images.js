const normalizeArtistName = (artistName) => {
  return artistName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
};

const getLocalArtistImage = (artistName) => {
  const directMatch = artistImageFiles.get(artistName);
  if (directMatch) return `/images/${encodeURIComponent(directMatch)}`;

  const normalizedName = normalizeArtistName(artistName);
  const fallbackMatch = [...artistImageFiles.entries()].find(([name]) =>
    normalizeArtistName(name) === normalizedName
  );

  return fallbackMatch ? `/images/${encodeURIComponent(fallbackMatch[1])}` : '';
};

export { getLocalArtistImage };
